export type ParsedYouTubeVideo = {
  videoId: string
  embedUrl: string
  thumbnailUrl: string
};

const parseYouTubeTime = (value: string): number => {
  const trimmed = value.trim();
  if (!trimmed) {
    return 0;
  }

  if (/^\d+$/.test(trimmed)) {
    return Number(trimmed);
  }

  const match = trimmed.match(/^(?:(\d+)h)?(?:(\d+)m)?(?:(\d+)s)?$/i);
  if (!match) {
    return 0;
  }

  const hours = Number(match[1] || 0);
  const minutes = Number(match[2] || 0);
  const seconds = Number(match[3] || 0);
  return hours * 3600 + minutes * 60 + seconds;
};

export const toYouTubeVideo = (input: string): ParsedYouTubeVideo | null => {
  const value = input.trim();
  if (!value) {
    return null;
  }

  const directVideoId = value.match(/^[a-zA-Z0-9_-]{11}$/);
  if (directVideoId) {
    return {
      videoId: value,
      embedUrl: `https://www.youtube.com/embed/${value}`,
      thumbnailUrl: `https://i.ytimg.com/vi/${value}/hqdefault.jpg`,
    };
  }

  try {
    const url = new URL(value);
    const host = url.hostname.replace("www.", "").toLowerCase();

    let videoId = "";
    if (host === "youtu.be") {
      videoId = url.pathname.split("/").filter(Boolean)[0] || "";
    } else if (host === "youtube.com" || host === "m.youtube.com") {
      if (url.pathname === "/watch") {
        videoId = url.searchParams.get("v") || "";
      } else {
        const pathParts = url.pathname.split("/").filter(Boolean);
        if (pathParts[0] === "shorts" || pathParts[0] === "embed" || pathParts[0] === "live") {
          videoId = pathParts[1] || "";
        }
      }
    }

    if (!videoId || !/^[a-zA-Z0-9_-]{11}$/.test(videoId)) {
      return null;
    }

    const startSeconds = parseYouTubeTime(url.searchParams.get("t") || url.searchParams.get("start") || "");
    const embedUrl = new URL(`https://www.youtube.com/embed/${videoId}`);
    if (startSeconds > 0) {
      embedUrl.searchParams.set("start", String(startSeconds));
    }

    return {
      videoId,
      embedUrl: embedUrl.toString(),
      thumbnailUrl: `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`,
    };
  } catch {
    return null;
  }
};